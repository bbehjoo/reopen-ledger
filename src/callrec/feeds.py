"""Chainlink reference feeds for the stock tokens: discovery, phase aggregators, and the value at a time.

Discovery: Chainlink's published feed directory for Base lists the "Coinbase <TICKER>" feeds (market hours
`us_equities_24/5`) and three "(24/7)" feeds. `build_feeds` keeps those, maps each to its token by ticker,
and reads on chain, through the proxy: `phaseId()`, every `phaseAggregators(i)`, `decimals()`,
`description()` and `latestRoundData()`. Feeds change aggregator at a phase change, so the update stream
is ingested from every phase aggregator, and every settled value records the aggregator it came from.

Value at a time: the answer of the latest AnswerUpdated (any phase of the proxy) whose block time is at or
before t. Never round ids: proxy round ids are phase-prefixed and not contiguous.
"""

from __future__ import annotations

import bisect
import json
from dataclasses import dataclass
from datetime import UTC, datetime

import httpx
import yaml

from . import config, store
from .abi import decode_address, decode_string, decode_uint, enc_uint, selector, signed, words
from .rpc import USER_AGENT

DIRECTORY = "https://reference-data-directory.vercel.app/feeds-ethereum-mainnet-base-1.json"
STREAM = "feeds"


def fetch_directory() -> list[dict]:
    r = httpx.get(DIRECTORY, timeout=60, headers={"user-agent": USER_AGENT})
    r.raise_for_status()
    return r.json()


def coinbase_feeds(directory: list[dict]) -> list[dict]:
    out = []
    for f in directory:
        name = f.get("name") or ""
        if not name.startswith("Coinbase "):
            continue
        docs = f.get("docs") or {}
        ticker = name.removeprefix("Coinbase ").split(" ")[0]
        kind = "24/7" if "(24/7)" in name else ("24/5" if docs.get("marketHours") == "us_equities_24/5" else "other")
        out.append({
            "name": name,
            "ticker": ticker,
            "kind": kind,
            "proxy": f["proxyAddress"].lower(),
            "directory_aggregator": (f.get("contractAddress") or "").lower(),
            "heartbeat_s": f.get("heartbeat"),
            "deviation_pct": f.get("threshold"),
            "decimals": f.get("decimals"),
            "market_hours": docs.get("marketHours"),
            "path": f.get("path"),
        })
    return sorted(out, key=lambda r: (r["ticker"], r["kind"]))


def chain_check(rpc, feed: dict) -> dict:
    p = feed["proxy"]
    phase = decode_uint(rpc.eth_call(p, selector("phaseId()")))
    aggs = []
    for i in range(1, phase + 1):
        a = decode_address(rpc.eth_call(p, selector("phaseAggregators(uint16)") + enc_uint(i)))
        aggs.append({"phase": i, "aggregator": a})
    desc = decode_string(rpc.eth_call(p, selector("description()")))
    dec = decode_uint(rpc.eth_call(p, selector("decimals()")))
    w = words(rpc.eth_call(p, selector("latestRoundData()")))
    current = decode_address(rpc.eth_call(p, selector("aggregator()")))
    return {
        "phase_id": phase,
        "phase_aggregators": aggs,
        "current_aggregator": current,
        "description": desc,
        "decimals_onchain": dec,
        "latest": {"round_id": str(w[0]), "answer": str(signed(w[1])), "updated_at": w[3]},
    }


def build_feeds(rpc, tokens_by_symbol: dict[str, dict]) -> dict:
    rows = []
    for f in coinbase_feeds(fetch_directory()):
        f = dict(f)
        sym = f["ticker"] + "c"
        tok = tokens_by_symbol.get(sym)
        f["token_symbol"] = sym if tok else None
        f["token"] = tok["address"] if tok else None
        f["chain"] = chain_check(rpc, f)
        rows.append(f)
    return {
        "schema": "callrec-feeds/v1",
        "source": DIRECTORY,
        "built_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "feeds": rows,
    }


def load() -> list[dict]:
    return config.load_yaml("feeds.yaml")["feeds"]


def write(doc: dict) -> None:
    p = config.config_dir() / "feeds.yaml"
    head = ("# Generated by `callrec feeds build` from Chainlink's feed directory and on-chain reads through\n"
            "# each proxy. Edit only by re-running the build; every value has its source in this file.\n")
    p.write_text(head + yaml.safe_dump(doc, sort_keys=False, width=110), encoding="utf-8", newline="\n")


def aggregator_addresses(feeds: list[dict]) -> list[str]:
    return sorted({a["aggregator"] for f in feeds for a in f["chain"]["phase_aggregators"]})


@dataclass(frozen=True)
class Update:
    ts_ms: int
    block: int
    answer: int       # feed units (8 decimals)
    round_id: int     # aggregator round id (not the proxy's)
    aggregator: str
    updated_at: int


class Series:
    """Every update of one proxy (all phases), in time order."""

    def __init__(self, updates: list[Update], decimals: int = 8):
        self.updates = sorted(updates, key=lambda u: (u.block, u.round_id))
        self._ts = [u.ts_ms for u in self.updates]
        self.decimals = decimals

    def at(self, ts_ms: int) -> Update | None:
        """The latest update timed at or before ts_ms."""
        i = bisect.bisect_right(self._ts, ts_ms) - 1
        return self.updates[i] if i >= 0 else None

    def between(self, a_ms: int, b_ms: int) -> list[Update]:
        i = bisect.bisect_left(self._ts, a_ms)
        j = bisect.bisect_right(self._ts, b_ms)
        return self.updates[i:j]

    def price(self, u: Update | None) -> float | None:
        return None if u is None else u.answer / 10 ** self.decimals


def decode_answer_updated(row: dict) -> Update:
    t = row["topics"]
    return Update(
        ts_ms=row["ts_ms"],
        block=row["block"],
        answer=signed(int(t[1], 16)),
        round_id=int(t[2], 16),
        aggregator=row["address"],
        updated_at=words(row["data"])[0],
    )


def load_series(feeds: list[dict] | None = None, rows=None) -> dict[str, Series]:
    """proxy -> Series, from the raw `feeds` stream."""
    feeds = feeds if feeds is not None else load()
    agg_to_proxy = {a["aggregator"]: f["proxy"] for f in feeds for a in f["chain"]["phase_aggregators"]}
    topic = config.chain()["chainlink_events"]["AnswerUpdated"]
    by_proxy: dict[str, list[Update]] = {f["proxy"]: [] for f in feeds}
    for row in rows if rows is not None else store.read(STREAM):
        if not row["topics"] or row["topics"][0] != topic:
            continue
        proxy = agg_to_proxy.get(row["address"])
        if proxy:
            by_proxy[proxy].append(decode_answer_updated(row))
    dec = {f["proxy"]: int(f.get("decimals") or 8) for f in feeds}
    return {p: Series(u, dec[p]) for p, u in by_proxy.items()}


def dump_json(obj) -> str:
    return json.dumps(obj, indent=1, sort_keys=True)
